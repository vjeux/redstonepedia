//! `mctas circuit memory counter-v8`: carousel counter v8, generated from v7 for ironspec's
//! paired-lane frame (day-1 lane 2026-11-10; parent's request): all 7 lines leave ONE face (south,
//! +z) at the wiring columns (frame x -1, 2, 5, 8 = this design's x -4, -1, 2, 5), two per column at
//! two heights: the even lanes low (y 0), the odd lanes high (y 2).
//!
//! - v7's ring and taps mirrored front to back (z -> -z): the even lanes' taps (0 2 4 6) now face
//!   south; the odd lanes' taps (1 3 5) face north.
//! - v7's logic (the monostable fallback and the edge detector, everything south of the ring)
//!   turned a quarter (its branch, which ran north into the loop, now runs west) and moved east of
//!   the ring, the branch entering the loop's east end; its input lands at (10, 1, 3).
//! - Even lines: a 3-rt repeater at each tap (6 gt), then dust at y 0 stepping east to its column.
//! - Odd lines: a 1-rt repeater into a stone and a two-torch tower to y 3 (2 + 2 + 2 = 6 gt, the same
//!   latency as the even lines, so the transition gap is v7's), dust south over the ring's roof at y 3,
//!   one step down to y 2 and east to its column.

use crate::schedgen::{B, DUST, P3, STONE, rep, seg};
use anyhow::Result;
use mctas::design::Design;
use std::collections::BTreeMap;
use std::path::Path;

fn mirror_z(s: &str) -> String {
    clock::canon::rotate_state(&clock::canon::mirror_state(&clock::canon::rotate_state(s, 1)), 3)
}

pub fn generate(v7: &Path, out: &Path) -> Result<()> {
    let d7 = Design::load(v7)?;
    let mut b = B { blocks: BTreeMap::new(), ports: BTreeMap::new(), nbt: BTreeMap::new() };
    let odd_tap = |p: &P3| p[2] == -6 && [-2, 0, 2].contains(&p[0]) && p[1] <= 0;
    let ring_part = |p: &P3| p[2] <= -7 || odd_tap(p);
    let logic_at = |p: &P3| -> P3 { [p[2] + 10, p[1], -p[0] + 9] };
    for (p, s) in &d7.blocks {
        if ring_part(p) {
            b.put([p[0], p[1], -p[2]], &mirror_z(s))?;
        } else {
            b.put(logic_at(p), &clock::canon::rotate_state(s, 3))?;
        }
    }
    for (p, n) in &d7.block_entities {
        let q = if ring_part(p) { [p[0], p[1], -p[2]] } else { logic_at(p) };
        b.nbt.insert(q, n.clone());
    }
    let input = d7.ports.get("input").copied().unwrap_or([6, 1, 0]);
    b.ports.insert("input".into(), logic_at(&input));
    // even lines (taps at (x, 0, 9) facing north, output into (x, 0, 10)); the frame's x is this
    // design's x + 3 (columns -1, 2, 5, 8 = -4, -1, 2, 5 here)
    let even: [(&str, i32, Vec<P3>); 4] = [
        ("b0", -3, [seg([-3, 0, 11], [-4, 0, 11]), seg([-4, 0, 12], [-4, 0, 16])].concat()),
        ("b2", -1, seg([-1, 0, 11], [-1, 0, 16])),
        ("b4", 1, [seg([1, 0, 11], [1, 0, 13]), seg([2, 0, 13], [2, 0, 16])].concat()),
        ("b6", 3, [seg([3, 0, 11], [5, 0, 11]), seg([5, 0, 12], [5, 0, 16])].concat()),
    ];
    for (name, x, path) in even {
        b.on([x, 0, 10], &rep("north", 2))?;
        b.wire([x, 0, 10], &path, 0)?;
        let end = *path.last().unwrap();
        b.ports.insert(format!("output.{name}"), [end[0], end[1], end[2] + 1]);
    }
    // odd lines (taps at (x, 0, 6) facing south, output into (x, 0, 5))
    let odd: [(&str, i32, Vec<P3>); 3] = [
        ("b1", -2, [seg([-2, 2, 11], [-2, 2, 15]), seg([-1, 2, 15], [-1, 2, 16])].concat()),
        ("b3", 0, [seg([0, 2, 11], [0, 2, 13]), seg([1, 2, 13], [2, 2, 13]), seg([2, 2, 14], [2, 2, 16])].concat()),
        ("b5", 2, [seg([2, 2, 11], [5, 2, 11]), seg([5, 2, 12], [5, 2, 16])].concat()),
    ];
    for (name, x, low) in odd {
        // the tap powers a stone at (x, 0, 5) (strength 1 is enough for a torch): a two-torch
        // tower to y 3 (4 gt, like the even lines' 2-rt repeaters)
        b.put([x, 0, 5], STONE)?;
        b.put([x, 1, 5], "minecraft:redstone_torch[lit=true]")?;
        b.put([x, 2, 5], STONE)?;
        b.put([x, 3, 5], "minecraft:redstone_torch[lit=false]")?;
        // over the roof at y 3 (supports at y 2), then one step down to y 2
        b.wire([x, 3, 5], &seg([x, 3, 6], [x, 3, 10]), 0)?;
        b.wire([x, 3, 10], &low, 0)?;
        let end = *low.last().unwrap();
        b.ports.insert(format!("output.{name}"), [end[0], end[1], end[2] + 1]);
    }
    let _ = DUST;
    let mut d = Design::parse("name: carousel-counter-v8\n")?;
    d.blocks = b.blocks;
    d.ports = b.ports;
    d.block_entities = b.nbt;
    let header = "# Carousel counter v8 (day-1 lane 2026-11-10, generated by `mctas circuit memory counter-v8`\n\
# from v7; crates/circuit-memory/src/counter8.rs): v7 laid out for the paired-lane frame. All 7\n\
# lines leave the south face at the wiring columns (frame x = this design's x + 3: -1, 2, 5, 8):\n\
# even lanes low (y 0, a 2-rt repeater at the tap), odd lanes high (y 2: the tap powers a stone\n\
# under a two-torch tower to y 3, over the ring's roof, one step down), both 4 gt, so v7's\n\
# transition gap stands. The ring and taps are v7's mirrored front to back; v7's logic is turned a\n\
# quarter and moved east of the ring (its branch enters the loop's east end; input at 10 1 3).\n\
# The odd lines' roof (supports over the loop's dust) also covers the hopper tops in their columns.\n";
    std::fs::write(out, format!("{header}{}", d.to_text()))?;
    println!("{}: {} blocks", out.display(), d.blocks.len());
    Ok(())
}
